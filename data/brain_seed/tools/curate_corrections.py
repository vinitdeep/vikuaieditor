def main():
    rows, seen = [], set()
    for line in open(HERE / "work" / "corrections_raw.jsonl", encoding="utf-8"):
        d = json.loads(line)
        k = (d["lang"], d["wrong"], d["right"])
        if k in DROP:
            continue
        rows.append({"lang": d["lang"], "wrong": d["wrong"], "right": d["right"], "n": d["n"],
                     "safe": k not in UNSAFE, "source": "harvest", "reels": d["reels"]})
        seen.add(k)
    for lang, w, r, safe in SPLIT:
        if (lang, w, r) in seen:
            continue
        rows.append({"lang": lang, "wrong": w, "right": r, "n": 1, "safe": safe, "source": "split", "reels": []})
    rows.sort(key=lambda x: (x["lang"], -x["n"], x["wrong"]))
    with open(SEED / "caption_corrections.jsonl", "w", encoding="utf-8") as f:
        for x in rows:
            f.write(json.dumps(x, ensure_ascii=False) + "\n")
    from collections import Counter
    print(len(rows), Counter((x["lang"], x["safe"]) for x in rows))


if __name__ == "__main__":
    main()
